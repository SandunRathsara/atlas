import { isAbsolute } from "node:path";

// Every Release folder carries `bin/gh` and `bin/git-credential-atlas`. They
// are generated from here (never checked in) so the text has one source.

/** Second-line marker; `atlas gh` skips any PATH entry carrying it so it never re-runs itself. */
export const RELEASE_SHIM_MARKER = "# atlas-release-shim";

/** Shim path inside a Release folder → the `atlas` subcommand it runs. */
export const RELEASE_SHIMS = {
  "bin/gh": "gh",
  "bin/git-credential-atlas": "git-credential",
} as const;

export type ShimSubcommand = (typeof RELEASE_SHIMS)[keyof typeof RELEASE_SHIMS];

const shellQuote = (value: string) => `'${value.replace(/'/gu, `'"'"'`)}'`;

/** POSIX `sh` shim that execs `<binaryPath> <subcommand> "$@"`. `binaryPath` is the Release folder's own `atlas`. */
export const releaseShimText = (binaryPath: string, subcommand: ShimSubcommand) => {
  if (!isAbsolute(binaryPath) || binaryPath.includes("\n") || binaryPath.includes("\0")) {
    throw new Error("Release shim needs an absolute binary path");
  }
  return `#!/bin/sh\n${RELEASE_SHIM_MARKER} (generated by src/shims.ts; do not edit)\nexec ${shellQuote(binaryPath)} ${subcommand} "$@"\n`;
};
