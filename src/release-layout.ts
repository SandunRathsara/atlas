// The one place that turns a downloaded `atlas` binary into a Release folder.
// Used by the updater (staging and the surviving-service bundles) and by
// Phase 4 `atlas setup` (fresh install and adopt).
//
//   <releasesRoot>/atlas-<tag>/
//     atlas                    the binary, 0555, SHA-256 checked
//     RELEASE_METADATA.json    schema-2 metadata, 0444
//     bin/gh                   shim -> `<folder>/atlas gh`
//     bin/git-credential-atlas shim -> `<folder>/atlas git-credential`
//     bin/git                  host git wrapper enforcing the minimum version
//
// Order (security relevant):
//   1. copy the binary into a temp sibling `.atlas-<tag>.<random>.tmp`;
//   2. check size and SHA-256 of the COPY against the metadata (nothing runs
//      before this passes, and the checked bytes are the bytes that run);
//   3. make it 0555 and run `atlas version --json` with a minimal env, never as
//      root: under root it drops to `runAs` with setpriv;
//   4. refuse unless that identity equals `metadata.identity`;
//   5. write metadata and bin/*, make everything read-only, fsync, rename into
//      place, fsync the parent.
// An existing intact folder is returned unchanged; an existing folder that is
// not intact is refused (never overwritten).
import { createHash, randomBytes } from "node:crypto";
import {
  chmodSync,
  closeSync,
  copyFileSync,
  createReadStream,
  existsSync,
  fsyncSync,
  lstatSync,
  mkdirSync,
  openSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { isAbsolute, join, resolve } from "node:path";
import { assertReleaseMetadata, type ReleaseMetadata } from "./release.ts";
import { RELEASE_SHIMS, releaseShimText } from "./shims.ts";

export type ReleaseFolderRunAs = { user: string; group: string };

export type BuildReleaseFolderOptions = {
  /** Candidate binary (untrusted until its copy's SHA-256 matches). */
  binaryPath: string;
  metadata: ReleaseMetadata;
  /** Parent directory, e.g. `/opt/atlas/releases` or `/opt/atlas/services/releases`. */
  releasesRoot: string;
  /** Required when running as root: the unprivileged account that runs `atlas version --json`. */
  runAs?: ReleaseFolderRunAs;
  versionTimeoutMs?: number;
};

export const releaseFolderName = (metadata: ReleaseMetadata) => `atlas-${metadata.identity.tag}`;

const metadataText = (metadata: ReleaseMetadata) => `${JSON.stringify(metadata, null, 2)}\n`;

/** `bin/git`: runs host git (`ATLAS_REAL_GIT`, default `/usr/bin/git`) only if it is at least `minimum`. */
export const gitWrapperText = (minimum: string) => {
  const match = /^(\d{1,9})\.(\d{1,9})\.(\d{1,9})$/u.exec(minimum);
  if (!match) throw new Error("Git minimum version must be numeric X.Y.Z");
  const [major, minor, patch] = match.slice(1);
  return `#!/bin/sh
# atlas-git-wrapper (generated by src/release-layout.ts; do not edit)
# Runs host git only when it is at least ${minimum}.
real_git=\${ATLAS_REAL_GIT:-/usr/bin/git}
case "$real_git" in /*) ;; *) echo "Atlas Git wrapper requires an absolute ATLAS_REAL_GIT" >&2; exit 1 ;; esac
[ -x "$real_git" ] || { echo "Host git is unavailable at $real_git" >&2; exit 1; }
version=$("$real_git" --version 2>/dev/null) || { echo "Host git did not report a version" >&2; exit 1; }
version=\${version#git version }
major=\${version%%.*}; rest=\${version#*.}
minor=\${rest%%.*}; rest=\${rest#*.}
patch=\${rest%%[!0-9]*}
case "$major:$minor:$patch" in
  *[!0-9:]*|:*|*::*|*:) echo "Host git version is not numeric: $version" >&2; exit 1 ;;
esac
if [ "$major" -gt ${major} ] || { [ "$major" -eq ${major} ] && { [ "$minor" -gt ${minor} ] || { [ "$minor" -eq ${minor} ] && [ "$patch" -ge ${patch} ]; }; }; }; then
  exec "$real_git" "$@"
fi
echo "Atlas needs git ${minimum} or newer; $real_git is $major.$minor.$patch" >&2
exit 1
`;
};

/** Every non-binary file of a Release folder, keyed by relative path. */
const folderTexts = (folder: string, metadata: ReleaseMetadata) => {
  const binary = join(folder, "atlas");
  return {
    "RELEASE_METADATA.json": metadataText(metadata),
    ...Object.fromEntries(Object.entries(RELEASE_SHIMS).map(([path, subcommand]) => [path, releaseShimText(binary, subcommand)])),
    "bin/git": gitWrapperText(metadata.minimumHostTools.git),
  } as Record<string, string>;
};

const sha256File = (path: string) => new Promise<string>((resolveHash, reject) => {
  const hash = createHash("sha256");
  createReadStream(path).on("error", reject).on("data", (chunk) => hash.update(chunk)).on("end", () => resolveHash(hash.digest("hex")));
});

const fsyncPath = (path: string) => {
  const descriptor = openSync(path, "r");
  try {
    fsyncSync(descriptor);
  } finally {
    closeSync(descriptor);
  }
};

const removeTree = (path: string) => {
  if (!existsSync(path)) return;
  const writable = (current: string) => {
    const stat = lstatSync(current);
    if (stat.isSymbolicLink()) return;
    chmodSync(current, stat.isDirectory() ? 0o700 : 0o600);
    if (stat.isDirectory()) for (const name of readdirSync(current)) writable(join(current, name));
  };
  writable(path);
  rmSync(path, { recursive: true, force: true });
};

const regularFile = (path: string) => {
  const stat = lstatSync(path, { throwIfNoEntry: false });
  return stat !== undefined && stat.isFile() && !stat.isSymbolicLink() ? stat : null;
};

/** True when `folder` holds exactly this Release's files (no extras), read-only, with the expected binary hash. */
export const releaseFolderIntact = async (folder: string, metadata: ReleaseMetadata) => {
  const stat = lstatSync(folder, { throwIfNoEntry: false });
  if (!stat || !stat.isDirectory() || stat.isSymbolicLink() || (stat.mode & 0o222) !== 0) return false;
  const texts = folderTexts(folder, metadata);
  const entries = (path: string) => readdirSync(path).sort().join("\n");
  const binDirectory = lstatSync(join(folder, "bin"), { throwIfNoEntry: false });
  if (!binDirectory || !binDirectory.isDirectory() || binDirectory.isSymbolicLink() || (binDirectory.mode & 0o222) !== 0 ||
      entries(folder) !== ["RELEASE_METADATA.json", "atlas", "bin"].join("\n") ||
      entries(join(folder, "bin")) !== Object.keys(texts).filter((path) => path.startsWith("bin/")).map((path) => path.slice(4)).sort().join("\n")) {
    return false;
  }
  const binary = regularFile(join(folder, "atlas"));
  if (!binary || (binary.mode & 0o7777) !== 0o555 || binary.size !== metadata.asset.size) return false;
  for (const [path, text] of Object.entries(texts)) {
    const file = regularFile(join(folder, path));
    if (!file || (file.mode & 0o222) !== 0 || readFileSync(join(folder, path), "utf8") !== text) return false;
  }
  return await sha256File(join(folder, "atlas")) === metadata.asset.sha256;
};

const lookupId = (command: string[], label: string) => {
  const result = Bun.spawnSync(command, { stdout: "pipe", stderr: "ignore", env: { PATH: "/usr/bin:/bin" } });
  const value = result.exitCode === 0 ? result.stdout.toString().trim().split(":") : [];
  const id = Number(command[0] === "getent" ? value[2] : value[0]);
  if (!Number.isSafeInteger(id) || id < 0) throw new Error(`Unknown ${label}`);
  return id;
};

/**
 * argv prefix that runs a command as `runAs` when this process is root (empty otherwise).
 * Throws rather than let root run it.
 */
export const unprivilegedCommandPrefix = (runAs: ReleaseFolderRunAs | undefined) => {
  if (process.getuid?.() !== 0) return [];
  if (!runAs) throw new Error("Refusing to run a candidate binary as root: no service user was given");
  const uid = lookupId(["id", "-u", "--", runAs.user], `service user ${runAs.user}`);
  const gid = lookupId(["getent", "group", runAs.group], `service group ${runAs.group}`);
  if (uid === 0 || gid === 0) throw new Error("Refusing to run a candidate binary as root: the service user must be unprivileged");
  return ["setpriv", `--reuid=${uid}`, `--regid=${gid}`, "--clear-groups", "--inh-caps=-all", "--"];
};

const reportedIdentity = async (binary: string, runAs: ReleaseFolderRunAs | undefined, timeoutMs: number) => {
  const child = Bun.spawn([...unprivilegedCommandPrefix(runAs), binary, "version", "--json"], {
    cwd: "/",
    env: { PATH: "/usr/bin:/bin", LANG: "C" },
    stdin: "ignore",
    stdout: "pipe",
    stderr: "ignore",
    timeout: timeoutMs,
  });
  const [output, exitCode] = await Promise.all([new Response(child.stdout).text(), child.exited]);
  if (exitCode !== 0) throw new Error("The candidate binary could not report its release identity");
  try {
    return JSON.parse(output) as unknown;
  } catch {
    throw new Error("The candidate binary reported an unreadable release identity");
  }
};

const sameIdentity = (reported: unknown, metadata: ReleaseMetadata) => {
  const expected = metadata.identity;
  const value = reported as Record<string, unknown> | null;
  return !!value && typeof value === "object" && Object.keys(value).length === 5 &&
    value.published === true && value.tag === expected.tag && value.semver === expected.semver &&
    value.build === expected.build && value.gitSha === expected.gitSha;
};

/**
 * Builds (or confirms) `<releasesRoot>/atlas-<tag>` from a candidate binary and returns its absolute path.
 * Throws, leaving nothing behind, on a size/SHA-256 mismatch, an identity mismatch, or a non-intact existing folder.
 */
export const buildReleaseFolder = async (options: BuildReleaseFolderOptions) => {
  const metadata = assertReleaseMetadata(options.metadata);
  const releasesRoot = resolve(options.releasesRoot);
  if (!isAbsolute(options.releasesRoot) || releasesRoot === "/") throw new Error("Release folders need an absolute, non-root parent");
  const folder = join(releasesRoot, releaseFolderName(metadata));

  mkdirSync(releasesRoot, { recursive: true, mode: 0o755 });
  const parent = lstatSync(releasesRoot);
  if (!parent.isDirectory() || parent.isSymbolicLink()) throw new Error("The Release folder parent is unsafe");
  if (lstatSync(folder, { throwIfNoEntry: false })) {
    if (await releaseFolderIntact(folder, metadata)) return folder;
    throw new Error(`Release folder ${folder} already exists but does not match ${metadata.identity.tag}`);
  }

  if (!regularFile(resolve(options.binaryPath))) throw new Error("The candidate binary is missing");
  const temporary = join(releasesRoot, `.${releaseFolderName(metadata)}.${randomBytes(8).toString("hex")}.tmp`);
  try {
    mkdirSync(temporary, { mode: 0o755 });
    chmodSync(temporary, 0o755);
    const binary = join(temporary, "atlas");
    copyFileSync(resolve(options.binaryPath), binary);
    chmodSync(binary, 0o600);
    fsyncPath(binary);
    if (lstatSync(binary).size !== metadata.asset.size || await sha256File(binary) !== metadata.asset.sha256) {
      throw new Error("The candidate binary does not match its published SHA-256");
    }
    chmodSync(binary, 0o555);
    const reported = await reportedIdentity(binary, options.runAs, options.versionTimeoutMs ?? 15_000);
    if (!sameIdentity(reported, metadata)) {
      throw new Error("The candidate binary reports a different release identity than its metadata");
    }

    mkdirSync(join(temporary, "bin"), { mode: 0o755 });
    for (const [path, text] of Object.entries(folderTexts(folder, metadata))) {
      const target = join(temporary, path);
      writeFileSync(target, text, { mode: 0o600, flag: "wx" });
      chmodSync(target, path.startsWith("bin/") ? 0o555 : 0o444);
      fsyncPath(target);
    }
    chmodSync(join(temporary, "bin"), 0o555);
    fsyncPath(join(temporary, "bin"));
    chmodSync(temporary, 0o555);
    fsyncPath(temporary);
    renameSync(temporary, folder);
    fsyncPath(releasesRoot);
    return folder;
  } finally {
    if (existsSync(temporary)) removeTree(temporary);
  }
};
